DROP TABLE IF EXISTS racuni;
DROP TABLE IF EXISTS narudzbe;
DROP TABLE IF EXISTS dogadjaji;
DROP TABLE IF EXISTS postavke;
DROP TABLE IF EXISTS reset_tokeni;
DROP TABLE IF EXISTS korisnici;

CREATE TABLE korisnici (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    email         VARCHAR(120),
    ime           VARCHAR(60),
    prezime       VARCHAR(60),
    uloga         VARCHAR(20)  NOT NULL,
    oib           VARCHAR(11)
);

CREATE TABLE reset_tokeni (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    token      VARCHAR(128) NOT NULL,
    istjece    TIMESTAMP,
    iskoristen BOOLEAN      DEFAULT FALSE NOT NULL
);

CREATE TABLE postavke (
    username   VARCHAR(50) PRIMARY KEY,
    podsjetnik BOOLEAN     NOT NULL,
    sati_prije INT         NOT NULL,
    kanal      VARCHAR(20) NOT NULL
);

CREATE TABLE dogadjaji (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv     VARCHAR(200)  NOT NULL,
    mjesto    VARCHAR(120)  NOT NULL,
    datum     TIMESTAMP     NOT NULL,
    cijena    DECIMAL(10,2) NOT NULL,
    kapacitet INT           NOT NULL,
    prodano   INT           DEFAULT 0 NOT NULL
);

CREATE TABLE narudzbe (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dogadjaj_id     BIGINT        NOT NULL REFERENCES dogadjaji (id),
    kupac           VARCHAR(50)   NOT NULL,
    kolicina        INT           NOT NULL,
    ime_na_ulaznici VARCHAR(200)  NOT NULL,
    oib             VARCHAR(11),
    iznos           DECIMAL(10,2) NOT NULL,
    kreirano        TIMESTAMP     NOT NULL,
    autorizacija    VARCHAR(40)
);

-- Račun ostaje sačuvan i nakon storna narudžbe (knjigovodstvena evidencija).
CREATE TABLE racuni (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    narudzba_id BIGINT       NOT NULL,
    kupac       VARCHAR(50)  NOT NULL,
    datoteka    VARCHAR(200) NOT NULL
);
